function makeSets(
  prefix: string,
  rows: Array<{ weight: number; reps: number | string }>
): SetRow[] {
  return rows.map((row, index) => ({
    id: `${prefix}-${index + 1}`,
    label: `SERIE ${index + 1}`,
    weight: row.weight,
    reps: row.reps,
    completed: false,
  }));
}

function exercise(
  partial: Omit<WorkoutExercise, 'sets' | 'completedCount' | 'totalSets' | 'isCompleted'> & {
    rows: Array<{ weight: number; reps: number | string }>;
  }
): WorkoutExercise {
  const { rows, ...rest } = partial;
  const sets = makeSets(String(rest.id), rows);
  return {
    ...rest,
    sets,
    completedCount: 0,
    totalSets: sets.length,
    isCompleted: false,
  };
}

